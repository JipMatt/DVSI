        'INPUT(Vy);\n',
        'INPUT(Mmy);//MY ADDITION\n',
        'INPUT(Mpy);//MY ADDITION\n',
        'INPUT(Vz);\n',
        'INPUT(Mmz);//MY ADDITION\n',
        'INPUT(Mpz);//MY ADDITION\n',
        'OUTPUT(Density);\n',
        'OUTPUT(Vx);\n',
        'OUTPUT(Vy);\n',
        'OUTPUT(Vz);\n',
        r'//<\USER_DEFINED>',
        '\n',
        '//<INTERNAL>\n',
        'int __attribute__((unused))i;\n',
        'int __attribute__((unused))j;\n',
        'int __attribute__((unused))k;\n',
        'int __attribute__((unused))jact;\n',
        'int __attribute__((unused))jgh;\n',
        'int __attribute__((unused))kact;\n',
        'int __attribute__((unused))kgh;\n',
        'int lgh;\n',
        'int lghs;\n',
        'int lact;\n',
        'int lacts;\n',
        'int lacts_null_mirror;\n',
        'int lacts_null;\n',
        '//<\INTERNAL>\n',
        '\n',
        '//<EXTERNAL>\n',
        'real* density = Density->field_cpu;\n',
        'real* vx = Vx->field_cpu;\n',
        'real* mmx = Mmx->field_cpu;\n',
        'real* mpx = Mpx->field_cpu;\n',
        'real* vy = Vy->field_cpu;\n',
        'real* mmy = Mmy->field_cpu;\n',
        'real* mpy = Mpy->field_cpu;\n',
        'real* vz = Vz->field_cpu;\n',
        'real* mmz = Mmz->field_cpu;\n',
        'real* mpz = Mpz->field_cpu;\n',
        'real dt = StepTime;\n',
        'int size_x = Nx+2*NGHX;\n',
        'int size_y = Ny+2*NGHY;\n',
        'int size_z = NGHZ;\n',
        'int nx = Nx;\n',
        'int ny = Ny;\n',
        'int nz = Nz;\n',
        'int nghy = NGHY;\n',
        'int nghz = NGHZ;\n',
        'int pitch  = Pitch_cpu;\n',
        'int stride = Stride_cpu;\n',
        '//<\EXTERNAL>\n',
        '\n',
        '//<CONSTANT>\n',
        '// real xmin(Nx+2*NGHX+1);\n',
        '// real ymin(Ny+2*NGHY+1);\n',
        '// real zmin(Nz+2*NGHZ+1);\n',
        '//<\CONSTANT>\n',
        '\n',
        '//<MAIN_LOOP>\n',
        '\n',
        'i = j = k = 0;\n',
        'float damping = 1e-3;//damping after factor after 1 omega t\n',
        '\n',
        '#ifdef Z\n',
        'for(k=0; k<size_z; k++) {\n',
        '#endif\n',
        '#ifdef Y\n',
        '    for(j=0; j<size_y; j++) {\n',
        '#endif\n',
        '#ifdef X\n',
        '    for(i=0; i<size_x; i++) {\n',
        '#endif\n',
        '//<#>\n',
        '\n',
        '    lgh = i + j*pitch + (nz+nghz+k)*stride;\n',
        '    lghs = i + j*pitch + (nz+nghz+1+k)*stride;\n',
        '    lact = i + j*pitch + (nz+nghz-1-k)*stride;\n',
        '    lacts = i + j*pitch + (nz+nghz-2-k)*stride;\n',
        '    lacts_null = i + j*pitch + (nz+nghz)*stride;\n',
        '    lacts_null_mirror = i + j*pitch + (nz+nghz-1)*stride;\n',
        '    kgh = (nz+nghz+k);\n',
        '    kact = (nz+nghz-1-k);\n',
        '\n',
        '//CUSTOM BOUNDARIES\n',
        'if (damping < dt){\n',
        '    damping = dt+1e-11;\n',
        '}\n',
        'if (k == 0) {density[lgh] = (density[lact] - '+'{})*(1-dt/damping) + {}'.format(dens[3],dens[2])+';}\n',
        'if (k == 1) {density[lgh] = (density[lact] - '+'{})*(1-dt/damping) + {}'.format(dens[4],dens[1])+';}\n',
        'if (k == 2){density[lgh] = (density[lact] - '+'{})*(1-dt/damping) + {}'.format(dens[5],dens[0])+';}\n',
        'vx[lgh] = ((vx[lact] {} + SHEARPARAM*OMEGAFRAME*OMEGAFRAME*Ymed(j))*density[lact]/(density[lgh])) * (1-dt/damping) - SHEARPARAM*OMEGAFRAME*OMEGAFRAME*Ymed(j) {};\n'.format(max_x_act,max_x_ghst),  
