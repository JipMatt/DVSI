        '    vz[lgh] = (mmz[lact]+mpz[lacts])/(density[lgh]+density[lgh-stride]) * (1-dt/damping);\n', 
        '}\n',
        'vz[lacts_null] = vz[lacts_null_mirror] * (1-dt/damping);\n',
        '\n',
